-- StockSphere · Predictions (v2 submission model: direction-first)
--
-- Requires 20261019000100_profiles.sql.
--
-- Fairness rules, enforced here rather than trusted to the app:
--   * Predictions are written ONLY by the app server (service role), which
--     records the reference price itself from live data. Users cannot insert,
--     edit or delete predictions — a losing call cannot be hidden.
--   * A prediction is locked once saved: a trigger refuses any change except
--     one status move out of 'open', for every role including the server.
--   * Results (exit price, outcome, points) are not stored on this table;
--     Phase 2 adds an append-only prediction_resolutions table.
--   * Everyone can read every prediction: a track record is public.
--   * The reputation counters on profiles (pred_*) are maintained by the
--     server and are not writable by users.
--
-- Review before applying. This file creates the table from scratch and stops
-- if a predictions table already exists, so it never touches existing data.

do $$
begin
  if to_regclass('public.predictions') is not null then
    raise exception 'public.predictions already exists — use an additive migration, not this file.';
  end if;
end $$;

create table public.predictions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,

  -- One id per submission attempt, generated by the browser: a retried or
  -- double-clicked submit returns the same prediction instead of a second one.
  client_request_id uuid not null,

  asset_type text not null
    constraint predictions_asset_type check (asset_type in ('stock', 'index', 'etf', 'crypto')),
  symbol text not null
    constraint predictions_symbol_format check (symbol ~ '^[A-Z0-9][A-Z0-9.&-]{0,19}$'),
  direction text not null
    constraint predictions_direction check (direction in ('up', 'down', 'sideways')),
  horizon text not null
    constraint predictions_horizon check (horizon in ('1d', '1w', '1m')),

  -- Optional price target (UP/DOWN only).
  target_price numeric check (target_price is null or target_price > 0),
  note text constraint predictions_note_length check (note is null or char_length(note) <= 280),

  -- Reference (entry) price, captured by the server — never by the client.
  reference_price numeric not null check (reference_price > 0),
  reference_source text not null
    constraint predictions_reference_source check (reference_source in ('upstox', 'yahoo')),
  reference_mode text not null
    constraint predictions_reference_mode check (reference_mode in ('live', 'from_close')),
  reference_quote_time timestamptz not null,
  currency text,

  -- SIDEWAYS/flat band and the volatility it came from, frozen at submission.
  band_pct numeric not null check (band_pct > 0 and band_pct <= 10),
  volatility_pct numeric check (volatility_pct is null or volatility_pct >= 0),

  -- Expiry: N trading sessions for exchange-traded assets; an exact time for
  -- crypto. estimated_expiry_at is for display and "due" scanning only — the
  -- resolver finds the real Nth session from market data.
  expiry_sessions smallint
    constraint predictions_expiry_sessions check (expiry_sessions in (1, 5, 21)),
  expires_at timestamptz,
  estimated_expiry_at timestamptz not null,

  submitted_at timestamptz not null default now(),
  scoring_version text not null,

  status text not null default 'open'
    constraint predictions_status check (status in ('open', 'correct', 'incorrect', 'flat', 'void', 'review')),

  constraint predictions_request_unique unique (user_id, client_request_id),
  constraint predictions_sideways_no_target
    check (direction <> 'sideways' or target_price is null),
  constraint predictions_target_side check (
    target_price is null
    or (direction = 'up' and target_price > reference_price)
    or (direction = 'down' and target_price < reference_price)
  ),
  constraint predictions_expiry_kind check (
    (asset_type = 'crypto' and expires_at is not null and expiry_sessions is null)
    or (asset_type <> 'crypto' and expiry_sessions is not null and expires_at is null)
  ),
  constraint predictions_quote_not_future
    check (reference_quote_time <= submitted_at + interval '1 minute')
);

create index predictions_user_idx on public.predictions (user_id, submitted_at desc);
create index predictions_due_idx on public.predictions (estimated_expiry_at) where status = 'open';
create index predictions_symbol_idx on public.predictions (symbol, submitted_at desc);

comment on table public.predictions is
  'Members'' direction calls. Public read; created only by the app server; locked after insert (only status may move once out of open).';

-- ---------------------------------------------------------------- lock

-- Nothing about a prediction can change after insert except a single status
-- transition out of 'open'. A trigger, so it binds the service role too.
create or replace function public.predictions_lock()
returns trigger
language plpgsql
as $$
begin
  if old.status <> 'open' then
    raise exception 'prediction % is already resolved', old.id;
  end if;
  if (to_jsonb(new) - 'status') is distinct from (to_jsonb(old) - 'status') then
    raise exception 'only status may change on prediction %', old.id;
  end if;
  return new;
end;
$$;

create trigger predictions_lock
  before update on public.predictions
  for each row execute function public.predictions_lock();

